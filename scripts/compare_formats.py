"""Land the SAME legacy customer extract in every supported source format and compare the results.

    python scripts/compare_formats.py [--api http://localhost:8000] [--src mock_data/legacy_ar_customers.csv]

Writes the test files to mock_data/formats/, registers each through the running API (preview -> register ->
profile), then compares every landed snapshot with the reference (plain UTF-8 CSV): row count, column list,
inferred types, a content fingerprint of every value, and the per-column profile. Three deliberately broken
files are included to prove the comparison (and the control total) can actually fail. The report goes to
mock_data/format_comparison.md. Exit code 1 if a file that should match does not, or one that should differ does not.
"""

from __future__ import annotations

import argparse
import csv
import gzip
import hashlib
import io
import json
import sys
import zipfile
from pathlib import Path

import duckdb
import httpx
import pandas as pd
from openpyxl import Workbook

ROOT = Path(__file__).resolve().parent.parent
SYSTEM = "FORMAT_COMPARE"
USER = {"X-User": "format.tester"}


def load_rows(src: Path) -> tuple[list[str], list[list[str]]]:
    with src.open(newline="", encoding="utf-8") as fh:
        reader = csv.reader(fh)
        header = next(reader)
        rows = [r for r in reader]
    # characters that stress encodings and quoting; every format gets exactly the same values (cp1252-safe)
    name = header.index("CUST_NAME")
    for i in range(0, len(rows), 150):
        rows[i][name] = ("Müller & Söhne, \"Ltd\" " if i % 300 == 0 else "Café Ñandú ") + rows[i][name]
    return header, rows


def delimited(header, rows, delim, encoding, newline="\r\n") -> bytes:
    buf = io.StringIO()
    w = csv.writer(buf, delimiter=delim, lineterminator=newline)
    w.writerow(header)
    w.writerows(rows)
    return buf.getvalue().encode(encoding)


def xlsx(header, rows, banner=0) -> bytes:
    wb = Workbook()
    if banner:
        notes = wb.active
        notes.title = "Notes"
        notes.append(["Extract notes - not data"])
        ws = wb.create_sheet("Data")
        for n in range(banner):
            ws.append([f"AR customer export - banner line {n + 1}"])
    else:
        ws = wb.active
    ws.append(header)
    for row in rows:
        ws.append(row)
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def build_files(header, rows, out: Path) -> dict[str, dict]:
    """label -> {name, bytes, options, expect: 'match' | 'differ' | 'rejected'}"""
    widths = {c: max(len(r[i]) for r in rows) + 2 for i, c in enumerate(header)}
    layout, pos = [], 1
    for c in header:
        layout.append({"name": c, "start": pos, "width": widths[c]})
        pos += widths[c]
    fixed = "\n".join("".join(r[i].ljust(widths[c]) for i, c in enumerate(header)) for r in rows).encode("utf-8")
    dicts = [dict(zip(header, r)) for r in rows]
    zbuf = io.BytesIO()
    with zipfile.ZipFile(zbuf, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("export/customers.csv", delimited(header, rows, ",", "utf-8"))
    pq = out / "_ref.parquet"
    duckdb.connect().register("df", pd.DataFrame(rows, columns=header)).execute(f"COPY df TO '{pq.as_posix()}' (FORMAT parquet)")
    banner_csv = b"AR customer export\r\ngenerated by legacy job 4711\r\n" + delimited(header, rows, ",", "utf-8")

    def f(name, content, options=None, expect="match", control=True):
        return {"name": name, "bytes": content, "options": options or {}, "expect": expect, "control": control}

    return {
        "csv-utf8": f("customers_utf8.csv", delimited(header, rows, ",", "utf-8")),
        "csv-lf-endings": f("customers_lf.csv", delimited(header, rows, ",", "utf-8", "\n")),
        "csv-utf8-bom": f("customers_bom.csv", b"\xef\xbb\xbf" + delimited(header, rows, ",", "utf-8")),
        "semicolon-cp1252": f("customers_semicolon.txt", delimited(header, rows, ";", "cp1252")),
        "pipe-gzip": f("customers_pipe.psv.gz", gzip.compress(delimited(header, rows, "|", "utf-8"))),
        "tsv-utf16": f("customers_tab.tsv", b"\xff\xfe" + delimited(header, rows, "\t", "utf-16-le")),
        "csv-in-zip": f("customers.zip", zbuf.getvalue()),
        "excel": f("customers.xlsx", xlsx(header, rows)),
        "excel-banner-rows": f("customers_banner.xlsx", xlsx(header, rows, banner=2), {"sheet": "Data", "header_row": 3}),
        "csv-banner-rows": f("customers_banner.csv", banner_csv, {"skip_rows": 2}),
        "json-array": f("customers.json", json.dumps(dicts).encode()),
        "ndjson": f("customers.ndjson", "\n".join(json.dumps(d) for d in dicts).encode()),
        "fixed-width": f("customers.dat", fixed, {"format": "fixed", "columns": layout}),
        "parquet": f("customers.parquet", pq.read_bytes()),
        # --- must NOT match: proves the comparison is not vacuous
        "BAD-truncated-silent": f("bad_truncated.csv", delimited(header, rows[:-7], ",", "utf-8"), expect="differ", control=False),  # no control total: only the comparison can notice
        "BAD-one-value-changed": f("bad_changed.csv", delimited(header, [r[:3] + ["tampered@example.com"] + r[4:] if i == 500 else r for i, r in enumerate(rows)], ",", "utf-8"), expect="differ"),
        "BAD-control-total": f("bad_control.csv", delimited(header, rows[:-7], ",", "utf-8"), expect="rejected"),
    }


def fingerprint(parquet: Path) -> tuple[str, list[tuple]]:
    con = duckdb.connect()
    cols = [r[0] for r in con.execute("DESCRIBE SELECT * FROM read_parquet(?)", [str(parquet)]).fetchall()]
    select = ", ".join(f'nullif(trim("{c}"), \'\') AS "{c}"' for c in cols)
    data = con.execute(f"SELECT {select} FROM read_parquet(?)", [str(parquet)]).fetchall()
    h = hashlib.sha256()
    for row in data:
        h.update(repr(row).encode())
    return h.hexdigest(), data


def first_difference(ref: list[tuple], got: list[tuple], cols: list[str]) -> str:
    if len(ref) != len(got):
        return f"row count {len(got)} vs reference {len(ref)}"
    for i, (a, b) in enumerate(zip(ref, got)):
        if a != b:
            c = next(k for k in range(len(a)) if a[k] != b[k])
            return f"row {i + 1}, column {cols[c]}: {b[c]!r} vs reference {a[c]!r}"
    return "no difference"


def profile_view(p: dict) -> list:
    keep = ("column_name", "detected_type", "null_count", "distinct_count", "min_length", "max_length")
    return [[c.get(k) for k in keep] + [json.dumps(c.get("top_values"), sort_keys=True)] for c in p["columns"]]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--api", default="http://localhost:8000")
    ap.add_argument("--src", default=str(ROOT / "mock_data" / "legacy_ar_customers.csv"))
    ap.add_argument("--workspace", default=str(ROOT / "workspace"))
    args = ap.parse_args()

    out = ROOT / "mock_data" / "formats"
    out.mkdir(parents=True, exist_ok=True)
    header, rows = load_rows(Path(args.src))
    files = build_files(header, rows, out)
    (out / "_ref.parquet").unlink(missing_ok=True)
    for spec in files.values():
        (out / spec["name"]).write_bytes(spec["bytes"])
    print(f"{len(rows)} rows x {len(header)} columns -> {len(files)} files in {out}")

    client = httpx.Client(base_url=args.api, headers=USER, timeout=300)
    results: dict[str, dict] = {}
    for label, spec in files.items():
        r: dict = {"label": label, "file": spec["name"], "size": len(spec["bytes"]), "expect": spec["expect"]}
        results[label] = r
        form = {"system_name": SYSTEM, "table_name": "FMT_" + label.replace("-", "_").upper(), "primary_key_columns": "CUST_ID"}
        if spec["options"]:
            form["options"] = json.dumps(spec["options"])
        if spec["control"]:
            form["expected_rows"] = str(len(rows))  # the source system says: 1980 rows
        reg = client.post("/api/sources/register", data=form, files={"file": (spec["name"], spec["bytes"])})
        if reg.status_code != 201:
            r.update(status="REJECTED", detail=reg.json().get("detail", reg.text))
            continue
        body = reg.json()
        prof = client.post(f"/api/profile/{body['table_id']}")
        prof.raise_for_status()
        digest, data = fingerprint(Path(args.workspace) / "tables" / str(body["table_id"]) / "source.parquet")
        r.update(status="LANDED", table_id=body["table_id"], format=body["format"], rows=body["rows_landed"],
                 control=body["control_status"], warnings=body["warnings"], fingerprint=digest, data=data,
                 profile=profile_view(prof.json()), types={c["column_name"]: c["detected_type"] for c in prof.json()["columns"]},
                 columns=[c["column_name"] for c in prof.json()["columns"]])

    ref = results["csv-utf8"]
    problems = []
    for label, r in results.items():
        if r["status"] == "REJECTED":
            r["verdict"] = "REJECTED (as expected)" if r["expect"] == "rejected" else "REJECTED"
            if r["expect"] != "rejected":
                problems.append(f"{label}: unexpectedly rejected - {r['detail']}")
            continue
        diffs = []
        if r["columns"] != ref["columns"]:
            diffs.append(f"columns {r['columns']} vs {ref['columns']}")
        if r["types"] != ref["types"]:
            diffs.append("inferred types differ: " + ", ".join(f"{k}: {r['types'].get(k)} vs {v}" for k, v in ref["types"].items() if r["types"].get(k) != v))
        if r["fingerprint"] != ref["fingerprint"]:
            diffs.append("content differs - " + first_difference(ref["data"], r["data"], ref["columns"]))
        if r["profile"] != ref["profile"]:
            bad = [a[0] for a, b in zip(r["profile"], ref["profile"]) if a != b]
            diffs.append("profile differs in: " + ", ".join(bad or ["column count"]))
        r["diffs"] = diffs
        if r["expect"] == "match":
            r["verdict"] = "IDENTICAL" if not diffs else "DIFFERENT"
            if diffs:
                problems.append(f"{label}: " + "; ".join(diffs))
        else:  # expect differ
            r["verdict"] = "DIFFERS (as expected)" if diffs else "IDENTICAL"
            if not diffs:
                problems.append(f"{label}: should have differed from the reference but did not")
        if r["expect"] == "rejected":
            problems.append(f"{label}: should have been rejected by the control total but landed")

    # ---------------------------------------------------------------- report
    lines = ["# Source format comparison", "",
             f"Reference: `{ref['file']}` ({len(rows)} rows, {len(header)} columns). Control total ({len(rows)} rows) sent with every file except BAD-truncated-silent.", "",
             "| Format | File | KB | Format detected | Rows | Control total | Content fingerprint | Verdict |", "|---|---|---|---|---|---|---|---|"]
    for label, r in results.items():
        if r["status"] == "REJECTED":
            lines.append(f"| {label} | {r['file']} | {r['size'] // 1024} | - | - | - | - | {r['verdict']} |")
        else:
            lines.append(f"| {label} | {r['file']} | {r['size'] // 1024} | {r['format']} | {r['rows']} | {r['control']} | `{r['fingerprint'][:12]}` | {r['verdict']} |")
    lines += ["", "## Details", ""]
    for label, r in results.items():
        if r["status"] == "REJECTED":
            lines.append(f"- **{label}**: {r['detail']}")
        elif r.get("diffs") or r.get("warnings"):
            lines.append(f"- **{label}**: " + "; ".join(r.get("diffs", []) + [f"warning: {w}" for w in r.get("warnings", [])]))
    lines += ["", "## Reference profile (all identical formats share this)", "", "| Column | Type | Nulls | Distinct | Min len | Max len |", "|---|---|---|---|---|---|"]
    lines += [f"| {p[0]} | {p[1]} | {p[2]} | {p[3]} | {p[4]} | {p[5]} |" for p in ref["profile"]]
    report = "\n".join(lines) + "\n"
    (ROOT / "mock_data" / "format_comparison.md").write_text(report, encoding="utf-8")
    print(report)
    print("PROBLEMS:" if problems else "ALL AS EXPECTED")
    for p in problems:
        print(" -", p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
